#!/usr/bin/env python3
"""Generate an inspection-only report of compile-time config macros; does not alter gameplay.

Use normal preprocessor pass with a placeholder SDK to capture final macro *definitions*.
These are not runtime behavior nor optimization recommendations.
"""
import re
import shutil
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[1]
compiler = shutil.which('g++') or shutil.which('clang++')
if not compiler:
    raise SystemExit('Need g++ or clang++ to report actual preprocessor macro values')
command = [compiler,'-std=c++20','-E','-dM','-I',str(root/'src'),
           '-I',str(root/'tests/preprocess_stub'),str(root/'src/main.cpp')]
try:
    res = subprocess.check_output(command,text=True)
except subprocess.CalledProcessError as e:
    raise SystemExit('C++ preprocessor failed: ' + str(e))
macros = {}
for line in res.splitlines():
    m = re.match(r'#define (P_[A-Za-z0-9_]+)\s+(.+)',line)
    if m:
        macros[m.group(1)] = m.group(2)

# Find where each active macro is defined (may be both a tuned define + fallback).
locations = {}
for p in (root/'src').iterdir():
    if p.suffix not in ('.inc','.h','.cpp'):
        continue
    for n, line in enumerate(p.read_text(errors='replace').splitlines(),1):
        m = re.match(r'\s*#\s*define\s+(P_[A-Za-z0-9_]+)\b',line)
        if m:
            locations.setdefault(m.group(1),[]).append(f'{p.name}:{n}')

count_true = count_zero = count_other = 0
lines = ['# v53 compile-time configuration inventory', '',
         'Generated by `python tools/config_report.py` from the C++ preprocessor.',
         '', 'This reports macro **definitions**, not runtime options or actual active code paths.',
         'Nonzero macros may still be shadowed by `PR`, `P`, the map family, or early returns.',
         '', '| Macro | Expanded definition | Definition locations |', '| --- | --- | --- |']
for name, val in sorted(macros.items()):
    val=val.replace('\n',' ')
    loc=', '.join(locations.get(name,[])) or '(from build command)'
    lines.append(f'| `{name}` | `{val}` | {loc} |')
    if val.strip() == '0': count_zero+=1
    elif re.match(r'^-?\d+(?:\.\d+)?$',val.strip()): count_true+=1
    else: count_other+=1
lines.extend(['',f'Raw macro definitions: **{len(macros)}**; literal zero: {count_zero},',
              f'other numeric literal: {count_true}, expression/text: {count_other}.',
              '', 'Consult `CONFIGURATION.md` before changing any values.', ''])
out=root/'CONFIG_EFFECTIVE.md'
out.write_text('\n'.join(lines))
print(f'Wrote {out.relative_to(root)} for {len(macros)} P_* definitions')
