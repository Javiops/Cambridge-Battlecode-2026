# build_plan.py OUT.h: per map, per side, per 50-round bin, the top-10 winners' share of camp work on each CAMP
# (camp-hit champion-rounds scaled by (120 / camp max hp)^0.35, so slow strong camps do not outweigh quick clusters).
# Keyed by camp position, not by the replay's group id (the decoded group ids are wrong on some 2.0.0 maps).
import json, gzip, os, sys
W='/tmp/claude-0/w'; P=f'{W}/assets/pcassets'; NB=14; EXP=0.35
T=json.load(open(f'{P}/replays_t10/index.json'))
maps={}
for x in T:
    f=f'{W}/dec/t10fix/'+os.path.basename(x['file']).replace('.repl26a','.json.gz')
    if not os.path.exists(f): f=f'{W}/dec/t10/'+os.path.basename(x['file']).replace('.repl26a','.json.gz')
    if not os.path.exists(f): continue
    D=json.load(gzip.open(f)); camps=D['camps']; R=D['rounds']
    pos=[(k[3],k[4]) for k in camps]; scale=[(120.0/max(120,k[7]))**EXP for k in camps]; cid={k[0]:i for i,k in enumerate(camps)}
    m=maps.setdefault(x['map'], {'c':pos,'sp':{},'acc':{t:[[0.0]*len(pos) for _ in range(NB)] for t in (0,1)},'wt':{0:[0.0]*NB,1:[0.0]*NB},'n':0})
    if sorted(m['c'])!=sorted(pos): print('skip mismatch',x['map'],file=sys.stderr); continue
    perm=[m['c'].index(p) for p in pos]
    m['n']+=1
    team={c[0]:c[1] for c in R[0]['c']}
    for t in (0,1):
        P0=[(c[3],c[4]) for c in R[0]['c'] if c[1]==t]; m['sp'][t]=(sum(p[0] for p in P0)/len(P0), sum(p[1] for p in P0)/len(P0))
    H={t:[[0.0]*len(pos) for _ in range(NB)] for t in (0,1)}
    for r,dd in D['ck'].items():
        b=min(NB-1,int(r)//50)
        for key in dd:
            a,k=map(int,key.split('>'))
            if k in cid: H[team[a]][b][perm[cid[k]]]+=scale[cid[k]]
    for t,s in ((0,'a'),(1,'b')):
        if x[s+'_result']!='win': continue
        for b in range(NB):
            tot=sum(H[t][b])
            if tot<2: continue
            for i in range(len(pos)): m['acc'][t][b][i]+=H[t][b][i]/tot
            m['wt'][t][b]+=1
out=open(sys.argv[1],'w')
out.write('// plan_t10.h: generated by build_plan.py from top-10 vs top-10 replays (engine 2.0.0, 2026-10-27), winners only.\n')
out.write('// Per map and side: camp positions, spawn centre, and per 50-round bin (last bin = r650+) the share (0-255) of the\n')
out.write('// winners\' camp work on each camp (hit rounds x (120 / max hp)^0.35). The bot sums the camps of each of its groups.\n#pragma once\nnamespace plan_t10 {\n')
out.write(f'constexpr int NB = {NB};\nstruct Map {{ const char* name; int nc; int games; const unsigned char* cx; const unsigned char* cy; unsigned char sx[2], sy[2]; const unsigned char* share; }};\n')
names=[]
for name,m in sorted(maps.items()):
    if m['n']<1: continue
    nc=len(m['c']); idn=''.join(ch if ch.isalnum() else '_' for ch in name)
    sh=[]
    for t in (0,1):
        for b in range(NB):
            wt=m['wt'][t][b]
            sh+=[min(255,int(round(255*(m['acc'][t][b][i]/wt if wt else 0)))) for i in range(nc)]
    out.write(f'inline const unsigned char {idn}_cx[]={{{",".join(str(p[0]) for p in m["c"])}}};\ninline const unsigned char {idn}_cy[]={{{",".join(str(p[1]) for p in m["c"])}}};\ninline const unsigned char {idn}_sh[]={{{",".join(map(str,sh))}}};\n')
    names.append((name,idn,nc,m))
out.write('inline const Map MAPS[] = {\n')
for name,idn,nc,m in names:
    out.write(f'  {{"{name}", {nc}, {m["n"]}, {idn}_cx, {idn}_cy, {{{int(round(m["sp"][0][0]))},{int(round(m["sp"][1][0]))}}}, {{{int(round(m["sp"][0][1]))},{int(round(m["sp"][1][1]))}}}, {idn}_sh}},\n')
out.write('};\nconstexpr int NMAPS = sizeof(MAPS) / sizeof(MAPS[0]);\n}  // namespace plan_t10\n')
print(len(names),'maps',file=sys.stderr)
