# build_plan.py OUT.h: per map, per side, per 50-round bin, the top-10 teams' share of camp-hit champion-rounds on each camp group
import json, gzip, os, sys
from collections import defaultdict
W='/tmp/claude-0/w'; P=f'{W}/assets/pcassets'; NB=14
T=json.load(open(f'{P}/replays_t10/index.json'))
maps={}   # name -> {'g': [(x,y)], 'sp': {side:(x,y)}, 'acc': {side: [[sum share per group] per bin]}, 'wt': {side:[w per bin]}}
for x in T:
    f=f'{W}/dec/t10/'+os.path.basename(x['file']).replace('.repl26a','.json.gz')
    if not os.path.exists(f): continue
    D=json.load(gzip.open(f)); camps=D['camps']; R=D['rounds']
    G=defaultdict(list)
    for k in camps: G[k[2]].append((k[3],k[4]))
    gids=sorted(G); cen=[(sum(p[0] for p in G[g])/len(G[g]), sum(p[1] for p in G[g])/len(G[g])) for g in gids]
    gpos={g:i for i,g in enumerate(gids)}; c2g={k[0]:gpos[k[2]] for k in camps}
    m=maps.setdefault(x['map'], {'g':cen,'sp':{},'acc':{0:[[0.0]*len(gids) for _ in range(NB)],1:[[0.0]*len(gids) for _ in range(NB)]},'wt':{0:[0.0]*NB,1:[0.0]*NB},'n':0})
    if len(m['g'])!=len(cen): print('skip mismatch',x['map'],file=sys.stderr); continue
    m['n']+=1
    team={c[0]:c[1] for c in R[0]['c']}
    for t in (0,1):
        P0=[(c[3],c[4]) for c in R[0]['c'] if c[1]==t]; m['sp'][t]=(sum(p[0] for p in P0)/len(P0), sum(p[1] for p in P0)/len(P0))
    H={0:[[0.0]*len(gids) for _ in range(NB)],1:[[0.0]*len(gids) for _ in range(NB)]}
    for r,dd in D['ck'].items():
        b=min(NB-1,int(r)//50)
        for key in dd:
            a,k=map(int,key.split('>'))
            if k in c2g: H[team[a]][b][c2g[k]]+=1
    for t,s in ((0,'a'),(1,'b')):
        w=2.0 if x[s+'_result']=='win' else 1.0
        for b in range(NB):
            tot=sum(H[t][b])
            if tot<5: continue
            for i in range(len(gids)): m['acc'][t][b][i]+=w*H[t][b][i]/tot
            m['wt'][t][b]+=w
out=open(sys.argv[1],'w')
out.write('// plan_t10.h: generated by build_plan.py from top-10 vs top-10 replays (engine 2.0.0, 2026-10-27).\n')
out.write('// Per map and side: group centres, spawn centre, and per 50-round bin (last bin = r650+) the top-10 teams\'\n')
out.write('// share (0-255) of camp-hit champion-rounds on each group (winners weigh 2, losers 1).\n#pragma once\nnamespace plan_t10 {\n')
out.write(f'constexpr int NB = {NB};\nstruct Map {{ const char* name; int ng; int games; const unsigned char* gx; const unsigned char* gy; unsigned char sx[2], sy[2]; const unsigned char* share; }};\n')
names=[]
for name,m in sorted(maps.items()):
    if m['n']<2: continue
    ng=len(m['g']); idn=''.join(ch if ch.isalnum() else '_' for ch in name)
    gx=','.join(str(int(round(c[0]))) for c in m['g']); gy=','.join(str(int(round(c[1]))) for c in m['g'])
    sh=[]
    for t in (0,1):
        for b in range(NB):
            wt=m['wt'][t][b]
            row=[m['acc'][t][b][i]/wt if wt else 0 for i in range(ng)]
            sh+= [min(255,int(round(255*v))) for v in row]
    out.write(f'inline const unsigned char {idn}_gx[]={{{gx}}};\ninline const unsigned char {idn}_gy[]={{{gy}}};\ninline const unsigned char {idn}_sh[]={{{",".join(map(str,sh))}}};\n')
    names.append((name,idn,ng,m))
out.write('inline const Map MAPS[] = {\n')
for name,idn,ng,m in names:
    out.write(f'  {{"{name}", {ng}, {m["n"]}, {idn}_gx, {idn}_gy, {{{int(round(m["sp"][0][0]))},{int(round(m["sp"][1][0]))}}}, {{{int(round(m["sp"][0][1]))},{int(round(m["sp"][1][1]))}}}, {idn}_sh}},\n')
out.write('};\nconstexpr int NMAPS = sizeof(MAPS) / sizeof(MAPS[0]);\n}  // namespace plan_t10\n')
print(len(names),'maps', file=sys.stderr)
