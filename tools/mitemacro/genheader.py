# Build bots/<bot>/src/mite_macro.h from extract.py's output: one script per official map and side.
# For each map and side the Mite game with the fewest Mite deaths (then the longest) is used; a game played
# on the other side is mirrored with the map's symmetry. Usage: genheader.py SCRIPTS.json MAPSJ_DIR OUT.h
import json, sys
sc = json.load(open(sys.argv[1])); MAPSJ = sys.argv[2]
FAM = {'collision': 1, 'corners': 2, 'elkring': 3, 'expanse': 4, 'interlock': 5, 'lanes': 6, 'monolith': 7, 'packs': 8, 'rows': 9}
out = ['// Generated by tools/mitemacro/genheader.py from the 54 decoded Mite games (top-2 dissection, 2026-10-15). Do not edit.',
       '// Per official map and side: Mite\'s draft and, per champion, its ordered macro steps:',
       '//   C first-hit-round capture-round camp-x camp-y caprecall took-reward   farm the camp group that holds that camp tile',
       '//   R round x y                                              recall (not on a capture)',
       '//   T round altar-x altar-y                                  tribute at that altar',
       '#pragma once', 'namespace mitemacro {',
       'struct MStep { char k; short r0, r1, x, y; char cr, cap; };  // cr: recall on the capture tiles, cap: this champion took the reward',
       'struct MChamp { const char* name; const MStep* s; int n; const char* shop; };  // shop: Mite\'s emblems, family:stat:count, in buying order',
       'struct MScript { int family; int side; int ax, ay; const char* draft; const MChamp* champs; int nc; const char* src; };']
scripts = []
for mp, sides in sorted(sc.items()):
    m = json.load(open(f'{MAPSJ}/{mp}.json')); w, h, sym = m['w'], m['h'], m['sym']
    def tf(x, y):
        if sym in ('H', 'R180'): x = w - 1 - x
        if sym in ('V', 'R180'): y = h - 1 - y
        return x, y
    for side in ('a', 'b'):
        cands = [(c['deaths'], -c['rounds'], 0 if s == side else 1, s, c) for s, c in sides.items()]
        cands.sort(key=lambda t: t[:3])
        _, _, _, s, c = cands[0]
        mirror = s != side
        tag = f'{mp}_{side}'
        names = []
        for name, steps in c['champs'].items():
            rows = []
            for st in steps:
                if st[0] == 'D': continue
                if st[0] == 'C':
                    x, y = tf(st[3], st[4]) if mirror else (st[3], st[4]); rows.append(f"{{'C',{st[1]},{st[2]},{x},{y},{st[5]},{st[6]}}}")
                else:
                    x, y = tf(st[2], st[3]) if mirror else (st[2], st[3]); rows.append(f"{{'{st[0]}',{st[1]},{st[1]},{x},{y},0,0}}")
            out.append(f'inline constexpr MStep {tag}_{name}[] = {{' + ','.join(rows) + '};')
            names.append(name)
        out.append(f'inline constexpr MChamp {tag}_ch[] = {{' + ','.join(f'{{"{n}",{tag}_{n},{len(c["champs"][n]) - sum(1 for st in c["champs"][n] if st[0]=="D")},"{c["shops"].get(n, "")}"}}' for n in names) + '};')
        sa = m['spawnA']
        src = f"{c['match'][:8]} vs {c['opp'].encode('ascii','ignore').decode().strip()} ({c['res']}, {c['rounds']} rounds, {c['deaths']} deaths){' mirrored from side ' + s if mirror else ''}"
        scripts.append(f'{{{FAM[mp]},{0 if side == "a" else 1},{sa[0]},{sa[1]},"{",".join(c["draft"])}",{tag}_ch,{len(names)},"{src}"}}')
        print(tag, src)
out.append('inline constexpr MScript scripts[] = {' + ',\n    '.join(scripts) + '};')
out.append('}  // namespace mitemacro')
open(sys.argv[3], 'w').write('\n'.join(out) + '\n')
